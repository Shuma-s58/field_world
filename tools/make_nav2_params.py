#!/usr/bin/env python3
"""orne-box の nav2_params.yaml から「自己位置推定なし(オドメトリのみ)」用の設定を作る。

使い方:
  python3 tools/make_nav2_params.py \
      ~/ros2_ws/src/orne-box/orne_box_navigation_executor/config/params/nav2_params.yaml \
      config/nav2_params_odom_only.yaml
"""
import sys
import yaml

src, dst = sys.argv[1], sys.argv[2]
p = yaml.safe_load(open(src))

# 1) 使わないノード設定を削除(emcl2 / keepout マスク / collision_monitor)
for k in ("emcl2", "costmap_filter_info_server", "collision_monitor"):
    p.pop(k, None)

# 2) BT ファイルは絶対パス(/home/takumi/...)を、インストール先の参照に置き換える
bt = ("$(find-pkg-share orne_box_navigation_executor)"
      "/config/behavior_trees/navigate_w_replanning_and_recovery.xml")
nav = p["bt_navigator"]["ros__parameters"]
nav["default_nav_to_pose_bt_xml"] = bt
nav["default_nav_through_poses_bt_xml"] = bt

# 3) オドメトリは EKF 出力(実機の構成と同じ)を使う
ODOM = "odometry/filtered"
nav["odom_topic"] = ODOM
p["controller_server"]["ros__parameters"]["odom_topic"] = ODOM
p["velocity_smoother"]["ros__parameters"]["odom_topic"] = ODOM

# 4) global_costmap: 静的地図を使わず、odom 固定の rolling window にする
g = p["global_costmap"]["global_costmap"]["ros__parameters"]
g.pop("map_topic", None)
g["global_frame"] = "odom"
g["rolling_window"] = True
g["width"] = 100    # フィールドは約80m幅 (x: -39〜+40m)
g["height"] = 50
g["track_unknown_space"] = False
g["plugins"] = ["obstacle_layer", "inflation_layer"]
g.pop("static_layer", None)

# 5) 障害物センサ /low_scan はそのまま(シミュレーションでは MID360 の点群から作る)

with open(dst, "w") as f:
    f.write("# generated by tools/make_nav2_params.py from orne-box nav2_params.yaml\n")
    f.write("# localization なし (map->odom は static TF)\n")
    yaml.safe_dump(p, f, sort_keys=False, allow_unicode=True)
print("wrote", dst)
